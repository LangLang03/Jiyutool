#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CommandResult {
    pub success: bool,
    pub message: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub data: Option<serde_json::Value>,
}

impl CommandResult {
    pub fn success(message: &str) -> Self {
        Self {
            success: true,
            message: message.to_string(),
            data: None,
        }
    }

    pub fn success_with_data(message: &str, data: serde_json::Value) -> Self {
        Self {
            success: true,
            message: message.to_string(),
            data: Some(data),
        }
    }

    pub fn error(message: &str) -> Self {
        Self {
            success: false,
            message: message.to_string(),
            data: None,
        }
    }
}

pub fn format_utf16_le(content: &str) -> Vec<u8> {
    let encoded = encoding_rs::UTF_16LE.encode(content);
    encoded.0.to_vec()
}

pub fn build_msg_packet(message: &str) -> Vec<u8> {
    let mut packet = vec![0u8; PACKET_SIZE];
    packet[..PACKET_MSG_HEADER.len()].copy_from_slice(PACKET_MSG_HEADER);
    let encoded = format_utf16_le(message);
    let start = 56;
    let end = std::cmp::min(start + encoded.len(), PACKET_SIZE);
    packet[start..end].copy_from_slice(&encoded[..end - start]);
    packet
}

pub fn build_cmd_packet(command: &str) -> Vec<u8> {
    let mut packet = vec![0u8; PACKET_SIZE];
    packet[..PACKET_CMD_HEADER.len()].copy_from_slice(PACKET_CMD_HEADER);
    let encoded = format_utf16_le(command);
    let start = 578;
    if start + encoded.len() <= PACKET_SIZE {
        packet[start..start + encoded.len()].copy_from_slice(&encoded);
    }
    packet
}

pub fn build_reboot_packet() -> Vec<u8> {
    let mut packet = vec![0u8; PACKET_SIZE];
    packet[..PACKET_REBOOT_DATA.len()].copy_from_slice(PACKET_REBOOT_DATA);
    packet
}

pub fn build_shutdown_packet() -> Vec<u8> {
    let mut packet = vec![0u8; PACKET_SIZE];
    packet[..PACKET_SHUTDOWN_DATA.len()].copy_from_slice(PACKET_SHUTDOWN_DATA);
    packet
}
